function assertCatalog(items: readonly Hexagram[]) {
  if (items.length !== 64) {
    throw new Error(`六十四卦录入了 ${items.length} 卦`);
  }
  const numbers = new Set<number>();
  const keys = new Set<string>();
  for (const item of items) {
    if (item.number < 1 || item.number > 64) {
      throw new Error(`卦序越界 ${item.name}`);
    }
    if (numbers.has(item.number)) throw new Error(`卦序重复 ${item.number}`);
    if (keys.has(item.key)) throw new Error(`卦象重复 ${item.name} ${item.key}`);
    if (!/^[01]{6}$/.test(item.key)) throw new Error(`卦象无效 ${item.name}`);
    numbers.add(item.number);
    keys.add(item.key);
  }
  for (let number = 1; number <= 64; number += 1) {
    if (!numbers.has(number)) throw new Error(`缺少第 ${number} 卦`);
  }
  const byNumber = new Map(items.map((item) => [item.number, item]));
  const expect = (number: number, key: string, name: string) => {
    const item = byNumber.get(number);
    if (!item || item.key !== key || item.name !== name) {
      throw new Error(`第 ${number} 卦应为 ${name} ${key}，实际 ${item?.name} ${item?.key}`);
    }
  };
  expect(1, "111111", "乾");
  expect(2, "000000", "坤");
  expect(3, "100010", "屯");
  expect(11, "111000", "泰");
  expect(12, "000111", "否");
  expect(63, "101010", "既济");
  expect(64, "010101", "未济");
}

assertCatalog(HEXAGRAMS);

export const byLines = new Map(HEXAGRAMS.map((item) => [item.key, item]));

export function imageTitle(item: Hexagram): string {
  const upper = TRIGRAMS[item.upper];
  const lower = TRIGRAMS[item.lower];
  if (item.upper === item.lower) return `${upper.name}为${upper.nature}`;
  return `${upper.nature}${lower.nature}${item.name}`;
}

export function placement(item: Hexagram): string {
  return `上${TRIGRAMS[item.upper].name}下${TRIGRAMS[item.lower].name}`;
}
