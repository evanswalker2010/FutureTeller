import { TRIGRAMS, trigramKey, type TrigramId } from "@/lib/trigrams";

export type Hexagram = {
  number: number;
  name: string;
  upper: TrigramId;
  lower: TrigramId;
  key: string;
  judgment: string;
  image: string;
  comment: string;
  suited: string;
  avoid: string;
};

function hex(
  number: number,
  name: string,
  upper: TrigramId,
  lower: TrigramId,
  judgment: string,
  image: string,
  comment: string,
  suited: string,
  avoid: string,
): Hexagram {
  return {
    number,
    name,
    upper,
    lower,
    key: trigramKey(lower) + trigramKey(upper),
    judgment,
    image,
    comment,
    suited,
    avoid,
  };
}

